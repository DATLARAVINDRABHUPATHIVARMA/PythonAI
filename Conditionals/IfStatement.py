# This is a simple example of an if statement in Python. using a boolean variable to check if it is raining or not.
is_raining = True

if is_raining:
    print("It's raining. Take an umbrella.")

# if and else statement in Python.
score = int(input("Enter the score of John: "))
if score >= 100:
    print("John scored a century!")
else:
    print("John did not score a century.")